// Offline support for Learn AI.
//
// - App shell (index.html, scripts, styles, playground code): cache-first, from
//   a cache named after a hash of those files, so each deploy replaces it.
// - Pages under learn/: network-first, falling back to the saved copy. The app
//   also asks for every page in the reader's language to be saved ahead of time.
// - Google Fonts and the html2pdf script: saved the first time they load. The
//   first visit loads the fonts before this worker is in control, so the page
//   also sends its font stylesheets, and every font they list is saved.
//
// GitHub Pages serves the site from a subfolder, so every path here is relative
// to this file. The block below is written by `npm run build:pages`.

// shell:start (generated by scripts/build-pages.mjs)
const VERSION = '881336f3ecc9';
const SHELL = [
    'index.html',
    'styles.css',
    'app.js',
    'motion.js',
    'i18n-extra.js',
    'content-translations.js',
    'quiz-translations.js',
    'lessons-agents-rag.js',
    'manifest.json',
    'learn/pages.css',
    'playground/playground.css',
    'playground/playground.mjs',
    'playground/nn.mjs'
];
// Every language has a hub at learn/<lang>/ and one page per slug below it.
const PAGES_DIR = 'learn';
const LANGS = ['id', 'en', 'zh', 'es', 'ar', 'hi', 'pt', 'fr', 'de', 'ja', 'ko', 'ru', 'tr', 'it', 'vi'];
const PAGE_SLUGS = [
    'what-is-artificial-intelligence',
    'machine-learning-basics',
    'deep-learning-neural-networks',
    'natural-language-processing',
    'computer-vision',
    'prompt-engineering-basics',
    'ai-ethics-and-bias',
    'ai-career-guide',
    'reinforcement-learning',
    'generative-ai-large-language-models',
    'ai-in-healthcare',
    'ai-for-business-and-industry',
    'robotics-and-ai',
    'edge-ai-and-iot',
    'automl-and-no-code-ai',
    'ai-agents',
    'rag-and-llm-evaluation',
    'neural-network-playground'
];
// shell:end

const PREFIX = 'learn-ai-';
const SHELL_CACHE = `${PREFIX}shell-${VERSION}`;
// Pages are refreshed from the network on every visit, so their cache outlives
// a deploy; dropping it would lose the saved pages until the next warm-up.
const PAGES_CACHE = `${PREFIX}pages-v1`;
const RUNTIME_CACHE = `${PREFIX}runtime-v1`;
const CURRENT_CACHES = [SHELL_CACHE, PAGES_CACHE, RUNTIME_CACHE];

const BASE = new URL('./', self.location).href;
const INDEX_URL = new URL('index.html', BASE).href;
const SHELL_URLS = new Set(SHELL.map(file => new URL(file, BASE).href));
const PAGES_URL = new URL(PAGES_DIR + '/', BASE).href;

self.addEventListener('install', event => {
    event.waitUntil(
        caches.open(SHELL_CACHE)
            // 'reload' skips the HTTP cache, so the files match the hash in VERSION.
            .then(cache => cache.addAll([...SHELL_URLS].map(url => new Request(url, { cache: 'reload' }))))
            .then(() => self.skipWaiting())
    );
});

self.addEventListener('activate', event => {
    // Only touch our own caches: other projects on the same github.io origin share this storage.
    event.waitUntil(
        caches.keys()
            .then(keys => Promise.all(keys
                .filter(key => key.startsWith(PREFIX) && !CURRENT_CACHES.includes(key))
                .map(key => caches.delete(key))))
            .then(() => self.clients.claim())
    );
});

self.addEventListener('fetch', event => {
    const request = event.request;
    if (request.method !== 'GET') return;
    const url = new URL(request.url);

    if (url.origin === self.location.origin) {
        const href = url.origin + url.pathname;
        if (href === BASE || SHELL_URLS.has(href)) {
            event.respondWith(cacheFirst(request, SHELL_CACHE, href === BASE ? INDEX_URL : href));
        } else if (href.startsWith(PAGES_URL)) {
            event.respondWith(networkFirst(request, PAGES_CACHE));
        }
        return;
    }

    if (url.hostname === 'fonts.googleapis.com') {
        event.respondWith(staleWhileRevalidate(event, RUNTIME_CACHE, fetchFontStylesheet));
    } else if (url.hostname === 'fonts.gstatic.com'
        || (url.hostname === 'cdnjs.cloudflare.com' && url.pathname.includes('/html2pdf.js/'))) {
        event.respondWith(cacheFirst(request, RUNTIME_CACHE, request.url));
    }
});

// Pages send { type: 'save-for-offline', lang, fontStylesheets } on load, and
// the app again after a language change.
self.addEventListener('message', event => {
    const { type, lang, fontStylesheets } = event.data || {};
    if (type !== 'save-for-offline') return;
    event.waitUntil(Promise.all([
        LANGS.includes(lang) ? cachePages(lang) : null,
        Array.isArray(fontStylesheets) ? cacheFonts(fontStylesheets) : null
    ]).catch(() => {}));
});

async function cacheFirst(request, cacheName, key) {
    const cache = await caches.open(cacheName);
    const cached = await cache.match(key);
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok) await cache.put(key, response.clone());
    return response;
}

async function networkFirst(request, cacheName) {
    const cache = await caches.open(cacheName);
    try {
        const response = await fetch(request);
        if (response.ok) await cache.put(request, response.clone());
        return response;
    } catch (error) {
        const cached = await cache.match(request, { ignoreSearch: true });
        if (cached) return cached;
        throw error;
    }
}

async function staleWhileRevalidate(event, cacheName, load) {
    const cache = await caches.open(cacheName);
    const cached = await cache.match(event.request.url);
    const update = load(event.request.url).then(async response => {
        if (response.ok) await cache.put(event.request.url, response.clone());
        return response;
    });
    if (!cached) return update;
    event.waitUntil(update.catch(() => {}));
    return cached;
}

// Saves the hub, every lesson and the playground in one language, so links in
// the app keep working offline, along with the fonts those pages link. Pages
// already saved are left alone; visiting them online refreshes them.
async function cachePages(lang) {
    const cache = await caches.open(PAGES_CACHE);
    const base = `${PAGES_URL}${lang}/`;
    const fontStylesheets = new Set();
    for (const url of [base, ...PAGE_SLUGS.map(slug => `${base}${slug}/`)]) {
        if (await cache.match(url)) continue;
        const response = await fetch(url);
        if (!response.ok) continue;
        await cache.put(url, response.clone());
        const html = await response.text();
        for (const [, href] of html.matchAll(/href="(https:\/\/fonts\.googleapis\.com\/[^"]+)"/g)) {
            fontStylesheets.add(href.replace(/&amp;/g, '&'));
        }
    }
    await cacheFonts([...fontStylesheets]);
}

// The page links the stylesheet without CORS, which would give an opaque
// response. Google Fonts allows CORS, so fetch it that way to see the status and
// read the font URLs inside.
function fetchFontStylesheet(url) {
    return fetch(url, { mode: 'cors', credentials: 'omit' });
}

// Saves each Google Fonts stylesheet and every font file it lists, all
// subsets included, so text in any of the 15 languages keeps its type.
async function cacheFonts(stylesheets) {
    const cache = await caches.open(RUNTIME_CACHE);
    for (const url of stylesheets) {
        if (new URL(url).hostname !== 'fonts.googleapis.com') continue;
        const response = await fetchFontStylesheet(url);
        if (!response.ok) continue;
        await cache.put(url, response.clone());
        const css = await response.text();
        for (const [, font] of css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)) {
            if (await cache.match(font)) continue;
            const file = await fetch(font, { mode: 'cors', credentials: 'omit' });
            if (file.ok) await cache.put(font, file);
        }
    }
}
